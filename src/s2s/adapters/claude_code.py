"""Defensive, local-only parsing for Claude Code JSONL transcripts.

Claude Code's transcript format is undocumented and evolves between CLI releases.
This module deliberately treats every line as untrusted input: unknown records are
ignored, malformed JSON is logged and skipped, and no parser decision reaches a
database or an LLM.
"""

from __future__ import annotations

from collections import Counter, defaultdict
from dataclasses import dataclass
from datetime import datetime
import json
import logging
from pathlib import Path
from typing import Any, Iterator

from s2s.paths import claude_projects_dir, resolve_paths


LOGGER = logging.getLogger(__name__)

# These wrappers are generated by Claude Code rather than typed by the user. Keep
# the lists explicit so schema changes can be handled by adding one small entry.
SCAFFOLD_CONTENT_MARKERS = ("<local-command-caveat>",)
SCAFFOLD_PREFIXES = (
    "<command-",
    "<local-command-",
    "<local-environment-",
    "<system-reminder>",
    "<task-notification>",
    "<user-prompt-submit-hook>",
)
TOOL_TARGET_KEYS = ("file_path", "path", "command", "query", "pattern", "url", "target")


@dataclass(frozen=True)
class UserMessage:
    """A direct, human-authored Claude Code message safe for scanner input."""

    message: str
    uuid: str | None
    timestamp: str | None
    session_id: str
    project: str
    cwd: str | None
    git_branch: str | None
    cli_version: str | None


@dataclass(frozen=True)
class SessionMetadata:
    """Session aggregate values used by the meter without retaining raw content."""

    session_id: str
    project: str
    dominant_model: str | None
    direct_message_count: int
    user_message_count: int
    assistant_message_count: int
    first_timestamp: str | None
    last_timestamp: str | None
    duration_seconds: float | None
    malformed_line_count: int


@dataclass(frozen=True)
class ContextPackMetadata:
    """Transcript metadata needed to attribute a context pack."""

    session_id: str
    project: str
    cwd: str | None
    git_branch: str | None
    timestamp: str | None


@dataclass(frozen=True)
class ContextPack:
    """Bounded context for Stage 2, arranged in chronological sections."""

    preceding_request: str
    agent_activity_digest: str
    frustrated_message: str
    following_exchange: str
    metadata: ContextPackMetadata

    @property
    def session_id(self) -> str:
        return self.metadata.session_id

    @property
    def project(self) -> str:
        return self.metadata.project

    @property
    def cwd(self) -> str | None:
        return self.metadata.cwd

    @property
    def git_branch(self) -> str | None:
        return self.metadata.git_branch

    @property
    def timestamp(self) -> str | None:
        return self.metadata.timestamp

    @property
    def text_length(self) -> int:
        """Return the character total of the four bounded content sections."""

        return sum(
            len(section)
            for section in (
                self.preceding_request,
                self.agent_activity_digest,
                self.frustrated_message,
                self.following_exchange,
            )
        )


@dataclass(frozen=True)
class _TranscriptLine:
    """A parsed line plus its original position for stable transcript ordering."""

    data: dict[str, Any]
    position: int


def iter_sessions(base_dir: Path | None = None) -> Iterator[Path]:
    """Yield Claude Code JSONL transcripts below ``base_dir`` in stable order.

    Callers and tests can pass a directory explicitly. The default is only a path
    calculation; this function never creates the real Claude home directory.
    """

    root = Path(base_dir) if base_dir is not None else claude_projects_dir()
    if not root.is_dir():
        return
    yield from sorted(path for path in root.rglob("*.jsonl") if path.is_file())


def iter_archived_sessions(base_dir: Path | None = None) -> Iterator[Path]:
    """Yield archived JSONL transcripts, using the normal parser-compatible layout."""

    root = Path(base_dir) if base_dir is not None else resolve_paths().archive_dir
    yield from iter_sessions(root)


def extract_user_messages(path: Path) -> list[UserMessage]:
    """Extract de-duplicated direct human messages from one transcript.

    Tool results are encoded as ``user`` records too, but their array content is
    deliberately excluded along with metadata, sidechain, and scaffold records.
    """

    transcript_path = Path(path)
    project = _project_for_path(transcript_path)
    fallback_session_id = transcript_path.stem
    messages: list[UserMessage] = []
    seen: set[tuple[str, str | None, str]] = set()

    for parsed in _iter_json_lines(transcript_path):
        record = _direct_user_message(parsed.data, project, fallback_session_id)
        if record is None:
            continue
        key = (record.session_id, record.timestamp, record.message)
        if key in seen:
            continue
        seen.add(key)
        messages.append(record)

    return messages


def extract_session_metadata(path: Path) -> SessionMetadata:
    """Return tolerant session aggregates, including the malformed-line count."""

    transcript_path = Path(path)
    project = _project_for_path(transcript_path)
    fallback_session_id = transcript_path.stem
    models: Counter[str] = Counter()
    direct_message_count = 0
    user_message_count = 0
    assistant_message_count = 0
    timestamps: list[str] = []
    session_id = fallback_session_id
    malformed_line_count = [0]
    seen_direct: set[tuple[str, str | None, str]] = set()

    for parsed in _iter_json_lines(transcript_path, malformed_line_count):
        data = parsed.data
        line_type = data.get("type")
        if line_type not in {"user", "assistant"}:
            continue
        line_session_id = _string(data.get("sessionId"))
        if line_session_id is not None:
            session_id = line_session_id
        timestamp = _string(data.get("timestamp"))
        if timestamp is not None:
            timestamps.append(timestamp)

        if line_type == "user":
            user_message_count += 1
            direct = _direct_user_message(data, project, fallback_session_id)
            if direct is not None:
                key = (direct.session_id, direct.timestamp, direct.message)
                if key not in seen_direct:
                    seen_direct.add(key)
                    direct_message_count += 1
        else:
            assistant_message_count += 1
            message = _mapping(data.get("message"))
            model = _string(message.get("model")) if message is not None else None
            if model is not None:
                models[model] += 1

    first_timestamp, last_timestamp = _timestamp_bounds(timestamps)
    return SessionMetadata(
        session_id=session_id,
        project=project,
        dominant_model=_dominant_model(models),
        direct_message_count=direct_message_count,
        user_message_count=user_message_count,
        assistant_message_count=assistant_message_count,
        first_timestamp=first_timestamp,
        last_timestamp=last_timestamp,
        duration_seconds=_duration_seconds(first_timestamp, last_timestamp),
        malformed_line_count=malformed_line_count[0],
    )


def session_metadata(path: Path) -> SessionMetadata:
    """Compatibility-friendly name for :func:`extract_session_metadata`."""

    return extract_session_metadata(path)


def build_context_pack(path: Path, target_uuid: str, max_chars: int = 16_000) -> ContextPack:
    """Build a bounded Stage 2 context pack for ``target_uuid``.

    The parent chain supplies context before the incident. Descendants provide the
    following exchange; both paths are rendered without any raw tool-result output.
    When a UUID is missing or malformed, an empty-content pack is returned instead
    of allowing one corrupt transcript record to stop downstream processing.
    """

    transcript_path = Path(path)
    lines = list(_iter_json_lines(transcript_path))
    project = _project_for_path(transcript_path)
    fallback_session_id = transcript_path.stem
    by_uuid = {
        uuid: parsed
        for parsed in lines
        if (uuid := _string(parsed.data.get("uuid"))) is not None
    }
    target = by_uuid.get(target_uuid)
    metadata = _context_metadata(
        target.data if target is not None else {},
        lines,
        project,
        fallback_session_id,
    )

    if target is None:
        LOGGER.warning("Claude Code context target %s was not found in %s", target_uuid, transcript_path)
        return ContextPack("", "", "", "", metadata)

    ancestors = _ancestor_chain(target, by_uuid)
    preceding_index = _last_direct_user_index(ancestors[:-1], project, fallback_session_id)
    preceding_request = ""
    if preceding_index is not None:
        preceding = _direct_user_message(ancestors[preceding_index].data, project, fallback_session_id)
        preceding_request = preceding.message if preceding is not None else ""

    activity_start = preceding_index + 1 if preceding_index is not None else 0
    agent_activity_digest = _activity_digest(ancestors[activity_start:-1])
    target_message = _direct_user_message(target.data, project, fallback_session_id)
    frustrated_message = target_message.message if target_message is not None else _message_text(target.data)
    following_exchange = _following_exchange(target, lines, project, fallback_session_id)

    bounded = _truncate_oldest_first(
        (preceding_request, agent_activity_digest, frustrated_message, following_exchange),
        max_chars,
    )
    return ContextPack(*bounded, metadata)


def _iter_json_lines(path: Path, malformed_line_count: list[int] | None = None) -> Iterator[_TranscriptLine]:
    """Yield object lines and log every malformed JSON record without raising."""

    try:
        with path.open(encoding="utf-8") as transcript:
            for position, raw_line in enumerate(transcript):
                if not raw_line.strip():
                    continue
                try:
                    data = json.loads(raw_line)
                except json.JSONDecodeError:
                    if malformed_line_count is not None:
                        malformed_line_count[0] += 1
                    LOGGER.warning("Skipping malformed Claude Code JSONL line %s:%d", path, position + 1)
                    continue
                if isinstance(data, dict):
                    yield _TranscriptLine(data=data, position=position)
    except OSError as error:
        LOGGER.warning("Unable to read Claude Code transcript %s: %s", path, error)


def _direct_user_message(data: dict[str, Any], project: str, fallback_session_id: str) -> UserMessage | None:
    message = _mapping(data.get("message"))
    content = message.get("content") if message is not None else None
    if (
        data.get("type") != "user"
        or data.get("isMeta")
        or data.get("isSidechain")
        or message is None
        or message.get("role") != "user"
        or not isinstance(content, str)
        or _is_scaffold(content)
    ):
        return None

    return UserMessage(
        message=content,
        uuid=_string(data.get("uuid")),
        timestamp=_string(data.get("timestamp")),
        session_id=_string(data.get("sessionId")) or fallback_session_id,
        project=project,
        cwd=_string(data.get("cwd")),
        git_branch=_string(data.get("gitBranch")),
        cli_version=_string(data.get("version")),
    )


def _is_scaffold(content: str) -> bool:
    normalized = content.lstrip()
    return any(marker in content for marker in SCAFFOLD_CONTENT_MARKERS) or normalized.startswith(SCAFFOLD_PREFIXES)


def _ancestor_chain(target: _TranscriptLine, by_uuid: dict[str, _TranscriptLine]) -> list[_TranscriptLine]:
    """Return the target's root-to-leaf parent chain, stopping safely on cycles."""

    chain = [target]
    visited = {_string(target.data.get("uuid"))}
    current = target
    while (parent_uuid := _string(current.data.get("parentUuid"))) is not None:
        if parent_uuid in visited:
            LOGGER.warning("Claude Code transcript parentUuid cycle at %s", parent_uuid)
            break
        parent = by_uuid.get(parent_uuid)
        if parent is None:
            break
        chain.append(parent)
        visited.add(parent_uuid)
        current = parent
    chain.reverse()
    return chain


def _last_direct_user_index(
    lines: list[_TranscriptLine], project: str, fallback_session_id: str
) -> int | None:
    for index in range(len(lines) - 1, -1, -1):
        if _direct_user_message(lines[index].data, project, fallback_session_id) is not None:
            return index
    return None


def _activity_digest(lines: list[_TranscriptLine]) -> str:
    digest: list[str] = []
    for parsed in lines:
        data = parsed.data
        if data.get("type") != "assistant":
            continue
        tool_lines = _tool_use_lines(data)
        if tool_lines:
            digest.extend(tool_lines)
            continue
        text = _message_text(data)
        if text:
            digest.append(f"Assistant: {_brief(text, 360)}")
    return "\n".join(digest)


def _following_exchange(
    target: _TranscriptLine,
    lines: list[_TranscriptLine],
    project: str,
    fallback_session_id: str,
) -> str:
    children: dict[str, list[_TranscriptLine]] = defaultdict(list)
    for parsed in lines:
        parent_uuid = _string(parsed.data.get("parentUuid"))
        if parent_uuid is not None:
            children[parent_uuid].append(parsed)

    target_uuid = _string(target.data.get("uuid"))
    if target_uuid is None:
        return ""
    descendants: list[_TranscriptLine] = []
    queue = list(children.get(target_uuid, ()))
    visited = {target_uuid}
    while queue:
        current = queue.pop(0)
        uuid = _string(current.data.get("uuid"))
        if uuid is not None and uuid in visited:
            continue
        if uuid is not None:
            visited.add(uuid)
        descendants.append(current)
        if uuid is not None:
            queue.extend(children.get(uuid, ()))

    rendered: list[str] = []
    for parsed in sorted(descendants, key=lambda item: item.position):
        data = parsed.data
        direct = _direct_user_message(data, project, fallback_session_id)
        if direct is not None:
            rendered.append(f"User: {direct.message}")
        elif data.get("type") == "assistant":
            tool_lines = _tool_use_lines(data)
            if tool_lines:
                rendered.extend(tool_lines)
            text = _message_text(data)
            if text:
                rendered.append(f"Assistant: {text}")
    return "\n".join(rendered)


def _tool_use_lines(data: dict[str, Any]) -> list[str]:
    message = _mapping(data.get("message"))
    content = message.get("content") if message is not None else None
    if not isinstance(content, list):
        return []
    summaries: list[str] = []
    for block in content:
        if not isinstance(block, dict) or block.get("type") != "tool_use":
            continue
        name = _string(block.get("name")) or "tool"
        target = _tool_target(block.get("input"))
        summaries.append(f"Tool: {name}{f' — {target}' if target else ''}")
    return summaries


def _tool_target(value: object) -> str:
    if not isinstance(value, dict):
        return ""
    for key in TOOL_TARGET_KEYS:
        target = value.get(key)
        if isinstance(target, str) and target:
            return _brief(target, 180)
    return ""


def _message_text(data: dict[str, Any]) -> str:
    message = _mapping(data.get("message"))
    if message is None:
        return ""
    content = message.get("content")
    if isinstance(content, str):
        return content
    if not isinstance(content, list):
        return ""
    text_blocks = [
        block.get("text")
        for block in content
        if isinstance(block, dict) and block.get("type") == "text" and isinstance(block.get("text"), str)
    ]
    return "\n".join(text_blocks)


def _context_metadata(
    data: dict[str, Any],
    lines: list[_TranscriptLine],
    project: str,
    fallback_session_id: str,
) -> ContextPackMetadata:
    return ContextPackMetadata(
        session_id=_metadata_value(data, lines, "sessionId") or fallback_session_id,
        project=project,
        cwd=_metadata_value(data, lines, "cwd"),
        git_branch=_metadata_value(data, lines, "gitBranch"),
        timestamp=_metadata_value(data, lines, "timestamp"),
    )


def _metadata_value(data: dict[str, Any], lines: list[_TranscriptLine], key: str) -> str | None:
    direct_value = _string(data.get(key))
    if direct_value is not None:
        return direct_value
    for parsed in lines:
        value = _string(parsed.data.get(key))
        if value is not None:
            return value
    return None


def _truncate_oldest_first(sections: tuple[str, str, str, str], max_chars: int) -> tuple[str, str, str, str]:
    # The frustrated message (index 2) is the incident itself — a context pack
    # without it is useless to the Triager, so it is sacrificed dead last.
    remaining = max(0, max_chars)
    total = sum(len(section) for section in sections)
    result = list(sections)
    for index in (0, 1, 3, 2):
        if total <= remaining:
            break
        section = result[index]
        remove = min(len(section), total - remaining)
        result[index] = section[remove:]
        total -= remove
    return tuple(result)  # type: ignore[return-value]


def _project_for_path(path: Path) -> str:
    return path.parent.name


def _mapping(value: object) -> dict[str, Any] | None:
    return value if isinstance(value, dict) else None


def _string(value: object) -> str | None:
    return value if isinstance(value, str) else None


def _brief(text: str, limit: int) -> str:
    compact = " ".join(text.split())
    return compact if len(compact) <= limit else f"{compact[: limit - 1]}…"


def _dominant_model(models: Counter[str]) -> str | None:
    return max(models, key=models.get) if models else None


def _timestamp_bounds(timestamps: list[str]) -> tuple[str | None, str | None]:
    if not timestamps:
        return None, None
    parsed = [(timestamp, _parse_timestamp(timestamp)) for timestamp in timestamps]
    valid = [(timestamp, value) for timestamp, value in parsed if value is not None]
    if not valid:
        return timestamps[0], timestamps[-1]
    return min(valid, key=lambda item: item[1])[0], max(valid, key=lambda item: item[1])[0]


def _duration_seconds(first: str | None, last: str | None) -> float | None:
    if first is None or last is None:
        return None
    first_datetime = _parse_timestamp(first)
    last_datetime = _parse_timestamp(last)
    if first_datetime is None or last_datetime is None:
        return None
    return max(0.0, (last_datetime - first_datetime).total_seconds())


def _parse_timestamp(timestamp: str) -> datetime | None:
    try:
        return datetime.fromisoformat(timestamp.replace("Z", "+00:00"))
    except ValueError:
        return None
